function o = rd_plot_options(R,user,matFile)
%RD_PLOT_OPTIONS Default figure settings; any field can be overridden by user.
%   Style follows RIS_phase stage two: Times New Roman, 10 pt, compact tiles,
%   legends in a free corner or above the tiles, never on a curve.
c = R.config;
o = struct('fontName','Times New Roman','fontSize',10,'tileWidthIn',2.67, ...
    'tileHeightIn',2.37,'gridTileWidthIn',2.0,'gridTileHeightIn',1.75, ...
    'resolution',300,'visible','off','formats',{{'png','fig'}}, ...
    'outputFolder',fullfile(fileparts(matFile),'figures'),'lineWidth',1.1, ...
    'winnerLineWidth',2.1,'yLimits',[1e-5 1],'xPaddingDB',2, ...
    'mainDistanceM',c.main.distanceM,'mainWindMps',c.main.windMps, ...
    'mapHalfWidthM',c.maps.halfWidthM,'mapDecades',5,'mapColormap','turbo', ...
    'mcMarkerStepDB',4,'profileSchemes',{{'steering','robust_aber','max_power'}});
if nargin<2 || isempty(user), return; end
names = fieldnames(user);
for j = 1:numel(names)
    if ~isfield(o,names{j})
        error('rd:PlotOption','Unknown plot option "%s".',names{j});
    end
    o.(names{j}) = user.(names{j});
end
end
