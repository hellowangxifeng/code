function o = rd_plot_options(R,user,matFile)
%RD_PLOT_OPTIONS Default figure settings; any field can be overridden by user.
%   Style follows RIS_phase stage two: Times New Roman, 10 pt, 2.67 x 2.37 in
%   tiles, legends outside the curves.
o = struct('fontName','Times New Roman','fontSize',10,'tileWidthIn',2.67, ...
    'tileHeightIn',2.37,'resolution',300,'visible','off','formats',{{'png','fig'}}, ...
    'outputFolder',fullfile(fileparts(matFile),'figures'),'lineWidth',1.2, ...
    'turbulenceId',1,'curveWinds',[0 3 5],'yLimits',[1e-5 1], ...
    'mapDistanceM',7.5,'mapWindMps',5, ...
    'mapSchemes',{{'direct','steering','flat_top','robust_aber','sea_aware'}}, ...
    'mapDecades',4,'mapColormap','turbo', ...
    'timeDistanceM',7.5,'timeWindMps',5, ...
    'fixedPowerDBm',R.config.metrics.fixedPowerDBm, ...
    'cdfWindMps',5,'cdfPowerDBm',30,'cdfFloor',1e-4);
if nargin<2 || isempty(user), return; end
names = fieldnames(user);
for j = 1:numel(names)
    if ~isfield(o,names{j})
        error('rd:PlotOption','Unknown plot option "%s".',names{j});
    end
    o.(names{j}) = user.(names{j});
end
end
