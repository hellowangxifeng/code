function rd_check(c)
%RD_CHECK Fail early, with a readable message, before a long run.
try
    tooOld = isMATLABReleaseOlderThan("R2022a");
catch
    tooOld = true;
end
if tooOld
    error('rd:Release','RIS_dynamic needs MATLAB R2022a or newer (tiledlayout, clim, exportgraphics).');
end
if isempty(which('sobolset')) || isempty(which('ncx2cdf'))
    error('rd:Toolbox',['The Statistics and Machine Learning Toolbox is required ' ...
        '(sobolset, ncx2cdf), exactly as in RIS_phase.']);
end
if isempty(which('czt'))
    error('rd:Toolbox','The Signal Processing Toolbox is required (czt, used by rp_fourier_window).');
end
needed = {'rp_stage2_config','rp_mc','rp_illuminate','rp_phase','rp_trace','rp_paraxial', ...
    'rp_command','rp_carrier_landing','rp_incident_field','rp_receiver_window', ...
    'rp_fourier_window','rp_deposit_power','rp_phase_profile','rp_spot_stats', ...
    'rp_aperture_channel','rp_link_samples','rp_link_metrics','rp_fading_response', ...
    'rp_fresnel','rp_geometry','rp_layer_path','wris_mc','wris_reference','RIS_float', ...
    'RIS_wave_components','RIS_wave_field','RIS_flotation','get_default_sea_params', ...
    'Hen_Green','Table_abc'};
missing = needed(cellfun(@(n) isempty(which(n)),needed));
if ~isempty(missing)
    error('rd:Dependencies','Functions not found on the path: %s',strjoin(missing,', '));
end
assert(strcmp(c.phase.model,'linear'),'rd:Phase', ...
    'RIS_dynamic loads affine LC tiles; RIS_phase c.phase.model must be ''linear''.');
assert(c.source.power==1,'rd:Power','Use a 1 W reference source; sweep c.metrics.powerDBm instead.');
validateattributes(c.scene.distancesM,{'numeric'},{'vector','positive','finite','increasing'}, ...
    'rd_check','c.scene.distancesM');
validateattributes(c.scene.incidenceDeg,{'numeric'},{'scalar','>',0,'<',80});
validateattributes(c.sea.windsMps,{'numeric'},{'vector','>=',3,'<=',25,'increasing'}, ...
    'rd_check','c.sea.windsMps (sea_wave/RIS_float accepts 3-25 m/s)');
assert(ismember(c.main.distanceM,c.scene.distancesM) && ismember(c.main.windMps,c.sea.windsMps), ...
    'rd:Main','c.main.distanceM / c.main.windMps must be entries of the distance / wind grids.');
validateattributes(c.sea.freezeTimeS,{'numeric'},{'scalar','nonnegative','<=',c.ris.duration}, ...
    'rd_check','c.sea.freezeTimeS (inside the c.ris.duration motion record)');
assert(ismember(c.rx.placement,{'frozen','calm'}),'rd:Placement', ...
    'c.rx.placement must be ''frozen'' or ''calm''.');
validateattributes(c.rx.carrierMargin,{'numeric'},{'scalar','nonnegative','<',0.2});
assert(all(ismember(c.design.families,{'flat_top','robust'})) && ...
    all(ismember({'flat_top','robust'},c.design.families)),'rd:Families', ...
    'c.design.families must contain flat_top and robust.');
validateattributes(c.design.widthsM,{'numeric'},{'vector','positive','finite','increasing'});
counts = [c.study.samples c.mc.photons c.validation.photons c.direct.photons ...
    c.dynamic.chunkSize c.maps.bins c.wave.minBins c.wave.maxBins c.wave.coherentNeighbours];
validateattributes(counts,{'numeric'},{'integer','positive'});
assert(c.wave.minBins<=c.wave.maxBins,'rd:Bins','c.wave.minBins must not exceed c.wave.maxBins.');
validateattributes([c.wave.receiverHalfWidthM c.wave.pixelsPerRadius c.wave.beamletGuardLobes], ...
    {'numeric'},{'positive','finite'});
assert(c.wave.receiverHalfWidthM>=5*c.study.positionSigmaM+c.rx.apertureRadius-1e-12, ...
    'rd:Window','c.wave.receiverHalfWidthM must cover 5 sigma_p of jitter plus the aperture.');
validateattributes([c.surface.gridStep c.surface.marchStep c.surface.rootTolerance], ...
    {'numeric'},{'positive','finite'});
validateattributes(c.surface.gridHalfWidth,{'numeric'},{'scalar','nonnegative','finite'});
validateattributes([c.compress.positionM c.compress.directionCos c.capture.maxPairs], ...
    {'numeric'},{'positive','finite'});
assert(size(c.metrics.turbulence,2)==2 && iscellstr(c.metrics.turbulence),'rd:Turbulence', ...
    'c.metrics.turbulence must be an n-by-2 cell of {ocean, atmosphere} names.');
assert(all(ismember(c.metrics.turbulence(:),{'none','weak','strong'})),'rd:Turbulence', ...
    'Use none, weak or strong.');
assert(ismember(c.metrics.policy,{'per_power','design_power'}),'rd:Policy', ...
    'c.metrics.policy must be ''per_power'' or ''design_power''.');
validateattributes(c.metrics.powerDBm,{'numeric'},{'vector','increasing','finite'});
validateattributes(c.rank.targets,{'numeric'},{'numel',2,'>',0,'<',0.5});
end
