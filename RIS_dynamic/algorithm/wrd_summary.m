function [frameTable,caseTable] = wrd_summary(cases,c)
%WRD_SUMMARY Per-frame table and per-case, per-link statistics over time.
%   frameTable : one row per (wind, angle, frame), all links side by side.
%   caseTable  : one row per (wind, angle, link) with the time statistics
%                mean/std/median/min/max power, scintillation index
%                <P^2>/<P>^2-1, outage probability P(P_rx < threshold),
%                zero-hit fraction and the RIS gain over both direct links.
%   Links: 'roughDirect' (new), 'flatDirect' (old still-water baseline,
%   only if computed) and 'ris'.
threshold = c.metrics.outageThresholdW;
frameRows = cell(numel(cases),1);
caseRows = cell(numel(cases),1);
for id = 1:numel(cases)
    item = cases{id};
    f = item.frames(:);
    n = numel(f);
    direct = [f.direct];
    ris = [f.ris];
    hasFlat = ~isempty(f(1).flat);
    rep = @(v) repmat(v,n,1);
    slopes = vertcat(f.slope);
    T = table(rep(item.windMps),rep(item.windDirectionDeg),rep(item.txRotationXYDeg(1)), ...
        rep(item.txRotationXYDeg(2)),rep(item.nominalIncidenceDeg),[f.t].',[f.absoluteTime].', ...
        [f.etaM].',slopes(:,1),slopes(:,2),[f.risTiltDeg].',[f.bottomDryFraction].',[f.topWetFraction].', ...
        'VariableNames',{'windMps','windDirectionDeg','txRotationXDeg','txRotationYDeg', ...
        'nominalIncidenceDeg','tS','absoluteTimeS','etaCenterM','slopeXCenter','slopeYCenter', ...
        'risTiltDeg','risBottomDrySampleFraction','risTopWetSampleFraction'});
    T = [T,linkColumns('direct',direct), ...
        table([direct.tirPowerW].',[direct.incidentPowerW].',[direct.transmittedPowerW].', ...
        [direct.waveBlockedPowerW].',[direct.energyResidual].', ...
        'VariableNames',{'directTirW','directSeaIncidentW','directTransmittedW', ...
        'directWaveBlockedW','directEnergyResidual'})]; %#ok<AGROW>
    if hasFlat
        flat = [f.flat];
        T = [T,linkColumns('flat',flat), ...
            table([flat.tirPowerW].',[flat.incidentPowerW].',[flat.transmittedPowerW].', ...
            'VariableNames',{'flatTirW','flatSeaIncidentW','flatTransmittedW'})]; %#ok<AGROW>
    end
    T = [T,linkColumns('ris',ris), ...
        table([ris.incidentPowerW].',[ris.activePowerW].',[ris.transmittedPowerW].', ...
        [ris.saturatedPowerFraction].',[ris.overwashedExitPowerW].',[ris.waveBlockedPowerW].', ...
        [ris.energyResidual].', ...
        'VariableNames',{'risBoardIncidentW','risActiveW','risTransmittedW', ...
        'risSaturatedFraction','risOverwashedExitW','risWaveBlockedW','risWaterEnergyResidual'})]; %#ok<AGROW>
    frameRows{id} = T;

    stats = linkStats('roughDirect',direct,threshold);
    if hasFlat, stats = [stats;linkStats('flatDirect',[f.flat],threshold)]; end %#ok<AGROW>
    stats = [stats;linkStats('ris',ris,threshold)]; %#ok<AGROW>
    risMean = stats.meanW(strcmp(stats.link,'ris'));
    roughMean = stats.meanW(strcmp(stats.link,'roughDirect'));
    stats.risOverRoughDirectDb = repmat(10*log10(risMean/roughMean),height(stats),1);
    stats.risOverFlatDirectDb = NaN(height(stats),1);
    if hasFlat
        flatMean = stats.meanW(strcmp(stats.link,'flatDirect'));
        stats.risOverFlatDirectDb(:) = 10*log10(risMean/flatMean);
    end
    k = height(stats);
    caseRows{id} = [table(repmat(item.windMps,k,1),repmat(item.windDirectionDeg,k,1), ...
        repmat(item.txRotationXYDeg(1),k,1),repmat(item.txRotationXYDeg(2),k,1), ...
        repmat(item.nominalIncidenceDeg,k,1),repmat(item.significantWaveHeightM,k,1), ...
        'VariableNames',{'windMps','windDirectionDeg','txRotationXDeg','txRotationYDeg', ...
        'nominalIncidenceDeg','significantWaveHeightM'}),stats];
end
frameTable = vertcat(frameRows{:});
caseTable = vertcat(caseRows{:});
end

function T = linkColumns(prefix,links)
names = strcat(prefix,{'RxW','RxSEW','RxHits','RxBallisticW','RxScatterW','ApertureNoFovW'});
T = table([links.rxPowerW].',[links.powerSEW].',[links.hitCount].', ...
    [links.ballisticPowerW].',[links.scatterPowerW].',[links.rxOnlyApertureW].', ...
    'VariableNames',names);
end

function T = linkStats(name,links,threshold)
p = [links.rxPowerW].';
hits = [links.hitCount].';
se = [links.powerSEW].';
mu = mean(p);
si = NaN;
if mu>0, si = mean(p.^2)/mu^2-1; end
T = table(string(name),numel(p),mu,std(p),median(p),min(p),max(p), ...
    10*log10(mu/1e-3),si,mean(p<threshold),threshold,mean(hits==0), ...
    sqrt(mean(se.^2)),mean([links.ballisticPowerW])/max(mu,realmin), ...
    'VariableNames',{'link','frames','meanW','stdW','medianW','minW','maxW', ...
    'meanDbm','scintillationIndex','outageProbability','outageThresholdW', ...
    'zeroHitFraction','rmsFrameSEW','ballisticShare'});
end
