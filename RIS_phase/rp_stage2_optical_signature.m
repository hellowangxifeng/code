function key=rp_stage2_optical_signature(c)
%RP_STAGE2_OPTICAL_SIGNATURE Field-only provenance; fading never changes a field.
cfg=rmfield(c,{'study','output','plot','cache','version'});
cfg.transport=struct('robustExponent',c.study.robustExponent, ...
    'maximumTailPower',c.study.maximumTailPower);
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(unicode2native(jsonencode(cfg),'UTF-8'));
names={'rp_stage2_wave','rp_stage2_scene','rp_study_scene','rp_finite_phase','rp_zero_phase', ...
    'rp_phase','rp_command','rp_vertical_command','rp_carrier_landing', ...
    'rp_incident_field','rp_bsf_ballistic','rp_mc','rp_illuminate','rp_wave','rp_trace', ...
    'rp_layer_path','rp_paraxial','rp_fourier_window','rp_pixel_intensity', ...
    'rp_receiver_window','rp_deposit_power','rp_fresnel','rp_gauss_legendre', ...
    'wris_mc','wris_reference','wris_device','RIS_flotation','RIS_rotation'};
for j=1:numel(names), digest.update(unicode2native(fileread(which(names{j})),'UTF-8')); end
key=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
