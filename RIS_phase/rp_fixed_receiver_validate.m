function v=rp_fixed_receiver_validate(c,d,data,bank,unmodulated)
%RP_FIXED_RECEIVER_VALIDATE Independent samples, fixed geometry and legal phases.
target=data.receiverCenterXY; direction=data.receiverDirection;
samples=rp_link_samples(c,c.study.validationSamples,c.study.seed+703);
selected=unique(data.choice(:));selected=selected(selected>0); rows=zeros(numel(selected),5);
powerW=10.^((0:2.5:100)/10)/1000;energy=zeros(numel(bank),5);
for k=1:numel(bank)
    b=bank{k};p=b.phase;w=b.wave;
    assert(norm(b.receiverCenterXY-target)<1e-12 && norm(b.channel.nominalDirection-direction)<1e-12, ...
        'rp:FixedGeometry','Receiver moved between designs.');
    limit=floor(c.device.maxAngleDeg/c.device.angleStepDeg)*c.device.angleStepDeg;
    assert(max(abs(p.commandDeg),[],'all')<=limit+1e-12 && ...
        max(abs(p.commandDeg/.021-round(p.commandDeg/.021)),[],'all')<1e-9 && ...
        max(abs(p.gradientOverK0-sind(p.commandDeg)),[],'all')<1e-12 && ...
        all(p.phaseAtReferenceRad>=0 & p.phaseAtReferenceRad<2*pi) && ...
        all(p.phaseCurvature==0,'all'),'rp:FixedRealizedPhase','Device constraint failed.');
    residual=w.pupilPowerW+w.interfaceLossW+w.omittedBallisticPowerW-w.inputDirectPowerW;
    excess=sum(w.ballisticPixelMeanWm2,'all')*w.cellAreaM2/max(w.pupilPowerW,realmin)-1;
    energy(k,:)=[k,residual,excess,w.diagonalMapPowerW/max(w.pupilPowerW,realmin),w.unresolvedQuadraturePowerFraction];
end
assert(max(abs(energy(:,2)))<1e-10 && max(energy(:,3))<1e-3 && ...
    max(energy(:,4))<=1+1e-8 && max(energy(:,5))<c.detector.maximumUnresolvedPowerFraction, ...
    'rp:FixedEnergy','Fixed-window optical energy needs refinement.');
for j=1:numel(selected)
    k=selected(j);b=bank{k};
    assert(b.spot.r50M>=.02,'rp:FixedCore','Selected half-energy radius is below 2 cm.');
    assert(b.spot.r50M>=.025 || isfield(b,'refinement'),'rp:FixedCoreResolution','Boundary core lacks refinement.');
    h=rp_aperture_channel(c,d.geometry,b.wave,target,samples);
    independent=rp_fixed_receiver_metrics(c,h,powerW);
    design=rp_fixed_receiver_metrics(c,b.channel,powerW);
    rows(j,:)=[k,abs(independent.meanReceivedPowerW(1)/design.meanReceivedPowerW(1)-1), ...
        max(abs(independent.aber-design.aber)),max(abs(independent.op-design.op)),h.outsideMapApertureFraction];
end
statistics=array2table(rows,'VariableNames',{'candidate','relativeMeanPowerChange','ABERAbsoluteChange','OPAbsoluteChange','outsideMapApertureFraction'});
assert(max(rows(:,2))<.02 && max(rows(:,3))<.002 && max(rows(:,4))<.005 && max(rows(:,5))<1e-5, ...
    'rp:FixedStatistics','Independent fixed-frame statistics need more samples.');
assert(all(diff(data.curves{4}.aber)<=1e-12) && all(diff(data.curves{5}.op)<=1e-12));
assert(all(data.curves{4}.aber<=data.curves{2}.aber+1e-12) && ...
    all(data.curves{5}.op<=data.curves{2}.op+1e-12),'rp:FixedIncumbent','Known feasible incumbent was discarded.');
assert(all(data.curves{4}.aber>=data.aberFloor-1e-12) && all(data.curves{5}.op>=data.opFloor-1e-12));
assert(unmodulated.scatterPhotons>=600000000 && unmodulated.scatterIndependentABERDifference<.015 && ...
    unmodulated.scatterIndependentOPDifference<.03,'rp:FixedScatter','Weak baseline photon statistics failed.');
% Export only ACTUALLY selected phase programs, plus the U-RIS zero phase.
folder=fullfile(c.output,'fixed_receiver','phase_programs');if ~isfolder(folder),mkdir(folder);end
programIds=[0;selected];
for k=programIds.'
    if k==0,p=d.bank{1}.phase;else,p=bank{k}.phase;end
    T=array2table([p.unitIds,p.referenceXY,p.commandDeg,p.gradientOverK0,p.phaseAtReferenceRad], ...
        'VariableNames',{'unitId','referenceXM','referenceYM','commandXDeg','commandYDeg','gradientXOverK0','gradientYOverK0','pistonRad'});
    writetable(T,fullfile(folder,sprintf('candidate_%03d.csv',k)));
    phaseLUT=struct('electrodeCoordinateM',((1:14400)-7200.5)*1e-6, ...
        'pistonRad',p.phaseAtReferenceRad,'gradientOverK0',p.gradientOverK0, ...
        'referenceXY',p.referenceXY,'wavelengthM',c.source.wavelength,'periodRad',2*pi, ...
        'formula','mod(piston+k0*(b_x*(x-ref_x)+b_y*(y-ref_y)),2*pi)');
    save(fullfile(folder,sprintf('candidate_%03d_lut.mat',k)),'phaseLUT');
end
v=struct('status','numerical_passed_visual_review_pending','signature',data.fixedReceiverSignature, ...
    'receiverCenterXY',target,'receiverDirection',direction,'phasePolicy',data.phasePolicy, ...
    'candidateCount',numel(bank),'selectedCandidateCount',numel(selected),'programCount',numel(programIds), ...
    'statistics',statistics,'energy',array2table(energy,'VariableNames', ...
    {'candidate','balanceW','coherentExcess','diagonalCapture','unresolvedFraction'}), ...
    'scatterPhotons',unmodulated.scatterPhotons,'scatterIndependentABERDifference',unmodulated.scatterIndependentABERDifference, ...
    'scatterIndependentOPDifference',unmodulated.scatterIndependentOPDifference, ...
    'scatterBandwidthSensitivity',unmodulated.scatterBandwidthSensitivity, ...
    'unmodulatedTailEnvelopeWm2',unmodulated.tailIrradianceEnvelopeWm2);
folder=fullfile(c.output,'fixed_receiver');
writetable(statistics,fullfile(folder,'validation_statistics.csv'));writetable(v.energy,fullfile(folder,'validation_energy.csv'));
save(fullfile(folder,'validation.mat'),'v');
fid=fopen(fullfile(folder,'validation.json'),'w');clean=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(v,PrettyPrint=true));
end
