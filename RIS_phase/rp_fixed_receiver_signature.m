function signature=rp_fixed_receiver_signature(c,d,policy)
%RP_FIXED_RECEIVER_SIGNATURE Bind the receiver protocol, sources and curves.
study=c.study;if isfield(study,'signature'),study=rmfield(study,'signature');end
spec=struct('opticalSignature',rp_stage2_optical_signature(c),'geometry',d.geometry, ...
    'study',orderfields(study),'policy',policy,'commonCarrierMargin',.012);
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(unicode2native(jsonencode(spec),'UTF-8'));
names={'rp_fixed_receiver_phase','rp_fixed_receiver_case','rp_fixed_receiver_unmodulated', ...
    'rp_nonstationary_rect_bound','rp_fixed_scatter_mc','rp_fixed_scatter_batch','rp_fixed_scatter_full','rp_fixed_refine_unmodulated', ...
    'rp_fixed_receiver_metrics','rp_fixed_receiver_collect','rp_fixed_receiver_refinement', ...
    'rp_fixed_receiver_links','rp_fixed_receiver_signature','rp_aperture_channel','rp_link_samples', ...
    'rp_link_metrics','rp_fading_response','rp_turbulence'};
for k=1:numel(names),digest.update(unicode2native(fileread(which(names{k})),'UTF-8'));end
signature=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
