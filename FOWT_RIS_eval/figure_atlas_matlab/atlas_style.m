function atlas_style()
%ATLAS_STYLE Common MATLAB journal style for the atlas.
set(groot,'defaultAxesFontName','Microsoft YaHei');
set(groot,'defaultTextFontName','Microsoft YaHei');
set(groot,'defaultAxesFontSize',14);
set(groot,'defaultAxesLineWidth',1.1);
set(groot,'defaultLineLineWidth',1.6);
set(groot,'defaultAxesBox','on');
set(groot,'defaultAxesTickDir','in');
set(groot,'defaultAxesXGrid','off','defaultAxesYGrid','off');
set(groot,'defaultFigureColor','w');
set(groot,'defaultAxesColorOrder',[0.00 0.45 0.74; 0.85 0.33 0.10; 0.00 0.62 0.45; ...
    0.49 0.18 0.56; 0.93 0.69 0.13; 0.30 0.30 0.30]);
end
