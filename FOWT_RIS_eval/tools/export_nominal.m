%FX_EXPORT_NOMINAL Export the nominal RIS/link design to MAT for the replay.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(root,'RIS_phase'),fullfile(root,'FOWT_RIS_eval','src')); rp_setup();
S=load(fullfile(root,'RIS_phase','results','validated_optics','ris_spots.mat'));
s=S.s; c=s.config; q=s.cases{1}; g=q.geometry; a=q.illumination;
I=load(fullfile(root,'FOWT_RIS_eval','results','improved_curvature.mat'));
d=struct();
d.nWater=c.optics.nWater; d.nGlass=c.optics.nGlass; d.nAir=c.optics.nAir;
d.lambda=c.source.wavelength; d.hIn=c.ris.thickness*c.optics.screenFraction; d.hOut=c.ris.thickness-d.hIn;
d.zTop=c.ris.thickness; d.Lx=c.ris.Lx; d.Ly=c.ris.Ly;
d.pitchM=c.array.pitchM; d.apertureM=c.array.apertureM; d.count=c.array.count;
d.maxAngleDeg=c.device.maxAngleDeg; d.angleStepDeg=c.device.angleStepDeg;
d.B=d.nAir*sind(floor(d.maxAngleDeg/d.angleStepDeg)*d.angleStepDeg);
d.maxCmdDeg=floor(d.maxAngleDeg/d.angleStepDeg)*d.angleStepDeg;
d.rxPlaneZ=g.rxPlaneZ; d.pTx=g.pTx; d.pRis=g.pRis; d.RRis=g.RRis;
d.unitCenters=a.unitCenters; d.unitDirectPowerW=a.unitDirectPowerW; d.unitPowerW=a.unitPowerW;
d.activeIds=a.activeIds; d.referenceXY=a.referenceXY;
d.currentCommandDeg=q.phase.commandDeg; d.currentGradient=q.phase.gradientOverK0;
d.improvedU=I.p.targetDirectionWorld; d.improvedQ=[0.415 -0.680];
d.currentCenter=q.footprint.centerXY; d.currentRadius=q.footprint.radiusM;
d.improvedCenter=I.f.centerXY; d.improvedRadius=I.f.radiusM;
d.improvedCurvature=I.p.phaseCurvature;
d.currentX=q.wave.x; d.currentY=q.wave.y; d.currentI=q.wave.irradianceWm2;
d.improvedX=I.wave.x; d.improvedY=I.wave.y; d.improvedI=I.wave.irradianceWm2;
d.currentMapPower=q.wave.mapPowerW; d.improvedMapPower=I.wave.mapPowerW;
d.currentPupilPower=q.wave.pupilPowerW; d.improvedPupilPower=I.wave.pupilPowerW;
save(fullfile(root,'FOWT_RIS_eval','data','processed','nominal_design.mat'),'-struct','d','-v7');
fprintf('exported. pTx [%.4f %.4f %.4f], pRis [%.4f %.4f %.4f], rxPlaneZ %.4f\n',d.pTx,d.pRis,d.rxPlaneZ);
fprintf('current center [%.4f %.4f], improved [%.4f %.4f]\n',d.currentCenter,d.improvedCenter);
