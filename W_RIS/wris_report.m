function wris_report(s)
%WRIS_REPORT Save numerical evidence independent of figure layout.
c=s.config; [nr,nc]=size(s.panels);
records=cell(nr*nc,1); motionRows=cell(nr*(nc-1),1);
contact=cell(nr*(nc-1),1); count=0; nm=0;
for row=1:nr
    reference=s.panels{row,1}.out.geometry.projectedOrientationDeg;
    for col=1:nc
        count=count+1; p=s.panels{row,col}; o=p.out; g=o.geometry;
        a=p.initialRotationXYDeg;
        rotation=mod(g.projectedOrientationDeg-reference+90,180)-90;
        records{count}=struct('row',row,'column',col,'rotationXDeg',a(1),'rotationYDeg',a(2), ...
            'initialIncidenceDeg',p.initialIncidenceDeg,'windMps',p.windMps, ...
            'windDirectionDeg',p.windDirectionDeg,'site',string(p.phase),'timeS',g.time, ...
            'siteXM',p.site.center(1),'siteYM',p.site.center(2),'yawRisDeg',g.yawRisDeg, ...
            'actualIncidenceDeg',g.thetaDeg,'projectedOrientationDeg',g.projectedOrientationDeg, ...
            'orientationWithoutRisYawDeg',g.orientationWithoutRisYawDeg, ...
            'completeCoreOrientationDeg',o.directPlaneMetrics.orientationDeg, ...
            'capturedCoreOrientationDeg',o.directMetrics.orientationDeg,'rotationVsStaticDeg',rotation, ...
            'coreClippedFraction',o.coreClippedFraction,'capturedWithoutEggW',o.powerWithoutTurbulence, ...
            'capturedWithEggW',o.capturedPower,'completeCorePowerWithoutEggW',o.directPlanePowerWithoutTurbulence, ...
            'capturedCorePowerWithoutEggW',o.directPowerWithoutTurbulence,'axisHitXM',g.axisLocal(1), ...
            'axisHitYM',g.axisLocal(2),'energyResidual',o.energyResidual);
        if ~isempty(p.motion)
            nm=nm+1; m=p.motion; n=numel(m.t);
            motionRows{nm}=[repmat([row col a p.windMps p.windDirectionDeg p.site.center.'],n,1), ...
                m.t.',m.eta.',m.etaCenter.',p.tx.position.',p.tx.yaw.'];
            contact{nm}=struct('row',row,'column',col,'windMps',p.windMps, ...
                'directionDeg',p.windDirectionDeg,'maxTiltDeg',m.validity.maxTiltDeg, ...
                'maxBottomGapAbsM',m.validity.maxIncidentWaveBoardMismatchM, ...
                'bottomGapSampleFraction',m.validity.bottomGapSampleFraction, ...
                'topWettedSampleFraction',m.validity.topWettedSampleFraction, ...
                'minTopClearanceM',m.validity.minTopClearanceM);
        end
    end
end
summary=struct2table(vertcat(records{:}));
writetable(summary,fullfile(c.output,'snapshots.csv'));
names={'row','column','rotationXDeg','rotationYDeg','windMps','windDirectionDeg','siteXM','siteYM','timeS', ...
    'surgeM','swayM','heaveM','rollRad','pitchRad','yawRad','localSeaM','txXM','txYM','txZM','txYawRad'};
writetable(array2table(vertcat(motionRows{:}),'VariableNames',names),fullfile(c.output,'motion.csv'));
writetable(struct2table(vertcat(contact{:})),fullfile(c.output,'contact_diagnostics.csv'));
save(fullfile(c.output,'flotation_audit.mat'),'-struct','s','flotationAudit');
fid=fopen(fullfile(c.output,'RESULTS.md'),'w','n','UTF-8');
assert(fid~=-1,'wris:Report','Cannot open report.'); guard=onCleanup(@() fclose(fid));
fprintf(fid,'# RIS 下表面光强：绕 x/y 旋转入射方向\n\n');
h=RIS_flotation(c.ris);
fprintf(fid,'玻璃 %g×%g×%g m，整机质量 %.6f kg；静水底面 z=%.9f m、顶面 z=%.9f m。\n\n', ...
    c.ris.Lx,c.ris.Ly,c.ris.thickness,h.totalMassKg,h.glassBottomZ,h.glassTopZ);
fprintf(fid,'方向定义：全局 +z 先绕固定 x 轴转 αx，再绕固定 y 轴转 αy，均为右手正角。\n\n');
fprintf(fid,'d0 = [sin(αy)cos(αx); -sin(αx); cos(αy)cos(αx)]。初始入射角 θ0=acos(cos(αx)cos(αy))。\n\n');
fprintf(fid,'每格 %d 个光子；快照相对时间 %.2f s，绝对海浪时间 %.2f s。\n\n', ...
    c.mc.photons,c.sampling.comparisonTime,c.ris.startTime+c.sampling.comparisonTime);
fprintf(fid,'共 %d 行×%d 列。第1列静水且TX/RIS固定；其余列为配置中的风况，保留TX机体固定光轴和RIS六自由度运动。\n\n',nr,nc);
fprintf(fid,'站位选项 `%s`；默认各风况初始水平位置相同，同一风况的所有角度共用RIS运动轨迹。可在脚本选择峰/谷/坡面站位。\n\n',c.comparison.site);
fprintf(fid,'## 数值结果\n\n');
fprintf(fid,'|αx°|αy°|θ0°|U(m/s)|wind°|实际θ°|RIS yaw°|相对静水旋转°|核心截断%%|接收 I/H 积分(W)|\n');
fprintf(fid,'|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for k=1:height(summary)
    q=summary(k,:);
    fprintf(fid,'|%g|%g|%.3f|%g|%g|%.3f|%+.3f|%+.3f|%.2f|%.6f|\n', ...
        q.rotationXDeg,q.rotationYDeg,q.initialIncidenceDeg,q.windMps,q.windDirectionDeg, ...
        q.actualIncidenceDeg,q.yawRisDeg,q.rotationVsStaticDeg,100*q.coreClippedFraction,q.capturedWithoutEggW);
end
fprintf(fid,'\n两页共享绝对对数色标；默认显示平均信道 I/H，EGG快照 I 仍保存在 out.irradiance。功率由 P0/N 归一化。\n\n');
fprintf(fid,'白框为真实%g×%g m玻璃孔径；灰色为板外；白虚线为截断前未散射核心MC D4σ轮廓；白实线为当前几何主轴；深色点线为该行静水主轴。\n\n',c.ris.Lx,c.ris.Ly);
fprintf(fid,'板外光子保留在能量账本与完整核心统计中，不计入RIS光强。主光轴落在板外时，在图内标注真实板外坐标。\n\n');
fprintf(fid,'## 验证\n\n');
fprintf(fid,'透明水体完整核心投影轴比最大绝对误差：%.5g；每个角度均对照 1/cos(θ0)。\n\n',s.validation.maxProjectionRatioError);
fprintf(fid,'能量账本最大残差：%.5g；光强面积积分与接收功率最大差：%.5g W。\n\n', ...
    s.validation.maxEnergyResidual,s.validation.maxPowerIntegralErrorW);
fprintf(fid,'完整核心方向与几何方向满足统计容差；独立光子数收敛通过：%d。\n\n',s.validation.convergenceAgreement);
fprintf(fid,'近似水动力模型沿用sea_wave玻璃/浮框模型；静水配平不代表有浪时持续底湿顶干，接触诊断见contact_diagnostics.csv。光学计算终止于玻璃下表面，不包含玻璃内部传播或RIS调相。\n');
end
